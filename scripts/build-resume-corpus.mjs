// Manual, one-off. Reads the sibling Corus v2 corpus and writes a baked,
// typed snapshot module. NOT run at build time. Requires the sibling repo.
//   node scripts/build-resume-corpus.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
// Default: the sibling repo checked out next to the portfolio root. Set
// RESUME_CORPUS_DIR (absolute, or relative to this repo root) when the corpus
// lives elsewhere — e.g. when running from a git worktree, where `..` is the
// worktrees/ directory rather than the canonical repo parent.
const corpusDir = process.env.RESUME_CORPUS_DIR
  ? resolve(root, process.env.RESUME_CORPUS_DIR)
  : resolve(root, '../claude-job-application/corus-data-v2');

function toBulletId(engId, i) { return `${engId}.b${i + 1}`; }

async function main() {
  let engagementsYaml;
  try {
    engagementsYaml = await readFile(resolve(corpusDir, 'engagements.yaml'), 'utf8');
  } catch (err) {
    console.error(`Cannot read ${corpusDir}/engagements.yaml — is the sibling repo present?`);
    console.error(String(err.message || err));
    process.exit(1);
  }
  const { engagements = [] } = parse(engagementsYaml) ?? {};

  const corpus = {
    header: {
      name: 'Jeremy Capps',
      contacts: ['jeremy@nycwork.space', 'linkedin.com/in/jeremycapps', 'New York, NY'],
    },
    engagements: engagements.map((e) => ({
      id: e.id,
      organization: e.organization ?? '',
      roleContext: e.role_context ?? [],
      timePeriod: e.time_period ?? '',
      themes: e.themes ?? [],
      roleFit: {
        strongest: e.role_fit?.strongest ?? [],
        secondary: e.role_fit?.secondary ?? [],
      },
      caution: e.caution ?? [],
      bullets: (e.resume_bullets ?? []).map((text, i) => ({
        id: toBulletId(e.id, i),
        text: String(text).trim(),
        evidenceRefs: [],
        sourceRefs: [`engagements.yaml#${e.id}`],
      })),
    })),
    // Skills/education/projects are curated by hand for v1 (not in engagements.yaml).
    skills: [],
    education: [{ degree: "Bachelor's Degree, minor in Mathematics" }],
    projects: [],
  };

  const banner = '// GENERATED by scripts/build-resume-corpus.mjs — do not edit by hand.\n';
  const body = `import type { ResumeCorpus } from './resume-corpus';\n\nexport const RESUME_CORPUS: ResumeCorpus = ${JSON.stringify(corpus, null, 2)};\n`;
  await writeFile(resolve(root, 'api/_lib/resume-corpus.generated.ts'), banner + body, 'utf8');
  console.log(`Wrote api/_lib/resume-corpus.generated.ts (${corpus.engagements.length} engagements).`);
}

main();
